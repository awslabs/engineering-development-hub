"""
Publish mesh peer hostnames so that <cluster_id>.edh-mesh resolves locally.

This writes a sentinel-delimited managed block into /etc/hosts. A separate file
of its own would be tidier, and was the first approach, but glibc's `files`
source reads /etc/hosts and nothing else: making it consult an additional file
means either an extra nsswitch module or a local resolver, and both add a moving
part to the boot path for the sake of one block of text.

So the block is written into /etc/hosts, and the sentinels are what make that
safe. Everything between them belongs to this daemon and is rewritten wholesale
on every change; everything outside them is preserved byte for byte, so the OS,
the operator and any other tool keep their lines. The rewrite is atomic, and it
is skipped entirely when the content has not changed, so an unchanged mesh does
not touch the file's mtime.

See docs/cross_region/README.md for the mesh model.
"""

from __future__ import annotations
import logging
import os
import tempfile
from typing import List, Optional

from .models import DOMAIN_SUFFIX, Health, Lifecycle, Peer

logger = logging.getLogger("soca_logger")

HOSTS_FILE = "/etc/hosts"

# Everything between these two markers is owned by this daemon.
BEGIN_SENTINEL = "# BEGIN edh-overlay-managed-block"
END_SENTINEL = "# END edh-overlay-managed-block"

# Suffix attached to every overlay hostname. Imported from models rather than
# defined again here, so there is one definition of the name peers resolve each
# other by. Re-exported because callers and tests reference it from this module.
DOMAIN_SUFFIX = DOMAIN_SUFFIX


# ------------------------------------------------------------------------------
# Rendering
# ------------------------------------------------------------------------------


def render_block(
    *,
    mesh_id: str,
    peers: List[Peer],
    health_by_cluster: Optional[dict] = None,
) -> str:
    """
    Render the managed block's contents, without the sentinels.

    Includes ACTIVE peers, minus any the health subsystem reports UNAVAILABLE.
    A DEGRADED peer keeps its entry, matching the tunnel: a name that stops
    resolving is a harsher failure than a name that resolves to a peer which is
    currently slow.

    Each peer gets an IPv6 line and an IPv4 line under the same hostname, which
    is what lets a caller ask for either family and get an answer without
    knowing how the mesh is addressed.
    """
    health_by_cluster = health_by_cluster or {}
    lines: List[str] = [
        f"# Mesh: {mesh_id}",
        "# Generated by edh-overlay-daemon. Do not edit between the sentinels.",
        "",
    ]

    for peer in peers:
        if peer.lifecycle != Lifecycle.ACTIVE:
            continue
        if health_by_cluster.get(peer.cluster_id) == Health.UNAVAILABLE:
            continue
        # The schema validator defaults a missing prefix to the empty string and
        # never rejects a malformed one, so an ACTIVE row without a usable address
        # plan reaches here and makes controller_v6 raise. Unguarded, that aborted
        # the whole block and dropped the names of every other peer, so one bad
        # row cost name resolution across the mesh.
        #
        # Asked as "does the plan parse", not "is it non-empty". The emptiness
        # form let a hand-edited ':3::/64' through, and that raised in exactly the
        # way this guard was written to prevent. Peer.address_plan_error is shared
        # with the tunnel renderer so both agree on which rows are usable.
        plan_error = peer.address_plan_error
        if plan_error is not None:
            logger.warning(
                "skipping peer %s in the hosts block: %s",
                peer.cluster_id,
                plan_error,
            )
            continue

        # Built from the peer's own property rather than assembled here, so the
        # rendered name and Peer.hostname cannot diverge.
        hostname = peer.hostname
        lines.append(f"{peer.controller_v6:<40s} {hostname}")
        lines.append(f"{peer.controller_v4:<40s} {hostname}")

    return "\n".join(lines)


# ------------------------------------------------------------------------------
# Applying
# ------------------------------------------------------------------------------


def apply_to_hosts_file(
    rendered_block: str,
    *,
    hosts_path: str = HOSTS_FILE,
    dry_run: bool = False,
) -> bool:
    """
    Rewrite the managed block atomically. Returns True when the file changed.

    Written to a temporary file in the same directory, fsynced, then renamed
    over the original, because rename within one filesystem is atomic: no
    reader ever sees a half-written /etc/hosts, which on this file would mean
    name resolution failing across the whole machine.
    """
    existing_content = ""
    if os.path.exists(hosts_path):
        with open(hosts_path, "r") as f:
            existing_content = f.read()

    new_content = _splice(existing_content, rendered_block)

    if new_content == existing_content:
        return False

    if dry_run:
        logger.info(
            "dry run: would rewrite %s (%d bytes)", hosts_path, len(new_content)
        )
        return False

    directory = os.path.dirname(hosts_path) or "/"
    fd, tmp = tempfile.mkstemp(prefix=".edh-hosts-", dir=directory)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(new_content)
            f.flush()
            os.fsync(f.fileno())
        # mkstemp creates the file 0600, which on /etc/hosts would make every
        # non-root lookup fail, so the original's mode and ownership are carried
        # over before the rename rather than after it.
        try:
            original = os.stat(hosts_path)
            os.chmod(tmp, original.st_mode & 0o7777)
            os.chown(tmp, original.st_uid, original.st_gid)
        except (OSError, FileNotFoundError):
            # No original to copy from, so fall back to the conventional mode.
            os.chmod(tmp, 0o644)
        os.rename(tmp, hosts_path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise

    logger.info(
        "rewrote %s (managed block %d bytes)", hosts_path, len(rendered_block)
    )
    return True


def _splice(existing: str, block_body: str) -> str:
    """
    Replace the managed block in `existing`, or append one if none is present.

    Content outside the sentinels is preserved exactly. When the sentinels are
    damaged, this returns the file unchanged rather than guessing where the
    block was meant to end: a wrong guess would delete lines belonging to
    something else, and /etc/hosts is a file where that is expensive.
    """
    begin_idx = existing.find(BEGIN_SENTINEL)
    end_idx = existing.find(END_SENTINEL)

    new_block = f"{BEGIN_SENTINEL}\n{block_body.rstrip()}\n{END_SENTINEL}"

    if begin_idx == -1 and end_idx == -1:
        if existing and not existing.endswith("\n"):
            existing = existing + "\n"
        return existing + ("\n" if existing else "") + new_block + "\n"

    if begin_idx == -1 or end_idx == -1:
        logger.error(
            "%s has only one of the two managed-block sentinels, so the block's "
            "extent cannot be determined. Refusing to modify the file; repair "
            "the sentinels by hand.",
            HOSTS_FILE,
        )
        return existing

    if begin_idx > end_idx:
        logger.error(
            "%s has the managed-block sentinels in the wrong order. Refusing to "
            "modify the file; repair them by hand.",
            HOSTS_FILE,
        )
        return existing

    # Replace through the end of the END sentinel's line, including its newline,
    # so the splice does not leave a blank line behind on every rewrite.
    end_line_end = existing.find("\n", end_idx)
    if end_line_end == -1:
        end_line_end = len(existing)
    else:
        end_line_end += 1

    return existing[:begin_idx] + new_block + "\n" + existing[end_line_end:]


def write_for_peers(
    *,
    mesh_id: str,
    peers: List[Peer],
    health_by_cluster: Optional[dict] = None,
    hosts_path: str = HOSTS_FILE,
    dry_run: bool = False,
) -> bool:
    """
    Render and apply in one call. Returns whether the file changed.

    `dry_run` is forwarded rather than dropped. apply_to_hosts_file has always
    supported it and this wrapper did not accept it, so `serve --dry-run`
    suppressed the tunnel changes and rewrote /etc/hosts for real, against the
    flag's documented contract of applying nothing.
    """
    return apply_to_hosts_file(
        render_block(
            mesh_id=mesh_id, peers=peers, health_by_cluster=health_by_cluster
        ),
        hosts_path=hosts_path,
        dry_run=dry_run,
    )
