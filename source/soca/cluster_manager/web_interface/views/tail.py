# Standalone pop-out view
# ---------------------------------------------------------------------------
@tail.route("/file_explorer/tail/view", methods=["GET"])
@login_required
@feature_flag(flag_name="FILE_LIVE_TAIL", mode="view")
def view():
    """
    Full-page tail viewer intended to be opened in a separate browser window.
    The UID is validated server-side before rendering so an unauthorized or
    malformed token fails fast with a visible message rather than silently
    hanging on the SSE connection.

    Client JS in tail_viewer.html auto-starts the stream from ?uid=... when
    tail_standalone is set in the template context.
    """
    uid = request.args.get("uid", "")
    name = request.args.get("name", "")

    # Validate before rendering so we never open a pop-out that would fail
    # on the stream endpoint anyway.
    file_info, err = _resolve_file(uid)
    if err:
        # Render the page with a pre-populated error rather than a blank
        # viewer; the auto-start JS will see no uid and show the error.
        return render_template(
            "tail_page.html",
            uid="",
            display_name="",
            initial_error=err,
        )

    # Prefer the real filename if the caller didn't supply one.
    if not name:
        name = os.path.basename(file_info["path"])

    return render_template(
        "tail_page.html",
        uid=uid,
        display_name=name,
    )
